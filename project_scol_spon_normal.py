def dense_block(x, num_layers, growth_rate , size):
    for i in range(num_layers):
        conv = Conv2D(growth_rate, size , activation='relu', padding='same')(x)
        x = Concatenate(axis=-1)([x, conv])
    return x

def inception_module(x, filters):
    # Each branch is a different path in the inception module
    branch1 = Conv2D(filters, (1, 1), activation='relu', padding='same')(x)

    branch2 = dense_block(x, 2, growth_rate=32,size= (1,1))
    branch2 = dense_block(branch2, 2, growth_rate=32,size= (3,3))

    branch3 = dense_block(x, 2, growth_rate=32,size= (1,1))
    branch3 = dense_block(branch3, 2, growth_rate=32,size= (5,5))


    # Concatenate all the branches
    output = Concatenate(axis=-1)([branch1, branch2, branch3])
    return output


input_layer = Input(shape=(224, 224, 3))

